CREATE TABLE booking (
    id               VARCHAR(40)  PRIMARY KEY,
    customer_id      VARCHAR(60)  NOT NULL,
    quote_id         VARCHAR(60)  NOT NULL,
    idempotency_key  VARCHAR(100),
    status           VARCHAR(20)  NOT NULL,
    failure_reason   VARCHAR(500),
    total_minor      BIGINT       NOT NULL,
    currency         VARCHAR(3)   NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT       NOT NULL,
    CONSTRAINT uk_booking_idempotency UNIQUE (customer_id, idempotency_key)
);

CREATE INDEX idx_booking_customer ON booking (customer_id);
CREATE INDEX idx_booking_status ON booking (status);

CREATE TABLE booking_leg (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id       VARCHAR(40)  NOT NULL REFERENCES booking (id),
    leg_index        INT          NOT NULL,
    offer_id         VARCHAR(80)  NOT NULL,
    mode             VARCHAR(20)  NOT NULL,
    quantity         INT          NOT NULL,
    unit_price_minor BIGINT       NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    hold_id          VARCHAR(80),
    provider_ref     VARCHAR(80),
    failure_reason   VARCHAR(500),
    held_at          TIMESTAMP WITH TIME ZONE,
    released_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_leg_index UNIQUE (booking_id, leg_index)
);

-- evenements a publier sur Kafka, ecrits dans la meme transaction que le dossier
CREATE TABLE outbox_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      VARCHAR(40)   NOT NULL UNIQUE,
    aggregate_id  VARCHAR(40)   NOT NULL,
    event_type    VARCHAR(40)   NOT NULL,
    payload       VARCHAR(4000) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at  TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_outbox_pending ON outbox_event (published_at, id);
