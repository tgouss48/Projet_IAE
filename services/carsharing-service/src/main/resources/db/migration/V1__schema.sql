CREATE TABLE vehicle (
    id                VARCHAR(40)  PRIMARY KEY,
    city              VARCHAR(80)  NOT NULL,
    model             VARCHAR(80)  NOT NULL,
    daily_price_minor BIGINT       NOT NULL
);

CREATE TABLE reservation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_id      VARCHAR(60)  NOT NULL UNIQUE,
    booking_ref  VARCHAR(60)  UNIQUE,
    vehicle_id   VARCHAR(40)  NOT NULL REFERENCES vehicle (id),
    rental_date  DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_reservation_vehicle_date ON reservation (vehicle_id, rental_date);
